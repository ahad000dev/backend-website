const express = require("express")
const cors = require("cors")
const path = require("path")
const studentRoute = require("./routes/student.route")
const studentDB = require("./config/database")
require("dotenv").config()
const auth = require("./middleware/auth")
const { issueCsrfToken, requireCsrfToken } = require("./middleware/csrf")
const userRoute = require("./routes/user.route")
const app = express()
const port = Number(process.env.PORT) || 3010

app.use(express.urlencoded({ extended: false }))
app.use(express.json())
app.use(cors({ origin: true, credentials: true }))
app.use(issueCsrfToken)
app.use("/uploads", express.static(path.join(__dirname, "uploads")))
app.use(express.static(path.join(__dirname, "front_file")))
app.get("/api/csrf-token", (req, res) => res.json({ message: "CSRF token issued" }))
app.use("/api", requireCsrfToken)
app.use("/api/users",userRoute)
app.use(auth)
app.use("/api/student", studentRoute)
app.get("/", (req, res) => res.sendFile(path.join(__dirname, "front_file", "index.html")))
app.use((err, req, res, next) => {
    if (err) return res.status(400).json({ message: err.message || "Request failed" })
    next()
})

studentDB()
    .then(() => app.listen(port, () => console.log(`Server running at http://localhost:${port}`)))
    .catch((error) => {
        console.error("MongoDB connection failed:", error.message)
        process.exit(1)
    })
